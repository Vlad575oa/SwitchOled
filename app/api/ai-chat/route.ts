async function buildCatalogSection(): Promise<string> {
  const products = await prisma.product.findMany({
    where: { isVisible: { not: false } },
    select: { name: true, price: true, inStock: true, category: { select: { name: true } } },
    orderBy: [{ categoryId: "asc" }, { name: "asc" }],
  });

  if (products.length === 0) return "## 📦 КАТАЛОГ\n\nТовары временно недоступны.";

  type ProductRow = (typeof products)[number];
  const byCategory: Record<string, ProductRow[]> = {};
  for (const p of products) {
    const cat = p.category.name;
    if (!byCategory[cat]) byCategory[cat] = [];
    byCategory[cat].push(p);
  }

  const lines: string[] = [
    "## 📦 КАТАЛОГ (актуальные данные из сайта — предлагай ТОЛЬКО эти товары, ничего не выдумывай)",
  ];
  for (const [cat, items] of Object.entries(byCategory)) {
    lines.push(`\n### ${cat}`);
    const inStock = items.filter((p: ProductRow) => p.inStock);
    const outOfStock = items.filter((p: ProductRow) => !p.inStock);
    if (inStock.length > 0) {
      lines.push("В наличии:");
      for (const p of inStock) lines.push(`  - ${p.name} — ${p.price.toLocaleString("ru-RU")} ₽`);
    }
    if (outOfStock.length > 0) {
      lines.push("Под заказ (нет в наличии):");
      for (const p of outOfStock) lines.push(`  - ${p.name} — ${p.price.toLocaleString("ru-RU")} ₽`);
    }
  }
  lines.push(
    "\nПравило по наличию:",
    "- Если товар в наличии — можно сразу предлагать к покупке.",
    "- Если товар под заказ — скажи: \"Этот товар сейчас под заказ. Оставьте контакт — менеджер уточнит сроки и свяжется с вами.\"",
    "- Если товара нет в этом списке вообще — не предлагай его и не выдумывай."
  );

  return lines.join("\n");
}

